import { useEffect, useState } from 'react';
import apiFetch from '../lib/api';
import LoadingSpinner from '../components/LoadingSpinner';
import './SecurityPage.css';

const KC_AUTH_BASE = 'https://qa-sso.corenroll.com/realms/Corenroll-Test/protocol/openid-connect/auth';
const CLIENT_ID = 'account-console'; // Use account-console for AIA actions

export default function SecurityPage() {
  const [credentials, setCredentials] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    fetchCredentials();
  }, []);

  async function fetchCredentials() {
    try {
      const data = await apiFetch('/api/account/credentials');
      setCredentials(data.credentials || []);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  }

  async function removeCredential(id) {
    if (!confirm('Are you sure you want to remove this credential?')) return;
    try {
      await apiFetch(`/api/account/credentials/${id}`, { method: 'DELETE' });
      setCredentials(credentials.filter((c) => c.id !== id));
    } catch (err) {
      alert('Failed to remove credential: ' + err.message);
    }
  }

  function triggerAiaAction(action) {
    // Redirect user to Keycloak for Application Initiated Action
    const redirectUri = encodeURIComponent(window.location.href);
    window.location.href = `${KC_AUTH_BASE}?client_id=${CLIENT_ID}&redirect_uri=${redirectUri}&response_type=code&scope=openid&kc_action=${action}`;
  }

  if (loading) return <LoadingSpinner />;

  const passwords = credentials.filter((c) => c.type === 'password');
  const passkeys = credentials.filter((c) => c.type === 'webauthn' || c.type === 'webauthn-passwordless');
  const otps = credentials.filter((c) => c.type === 'otp');

  return (
    <div className="security-page">
      <div className="security-header">
        <h1 className="page-title">Security Settings</h1>
        <p className="security-subtitle">
          Manage your account security and authentication methods
        </p>
      </div>

      {error && <div className="alert alert-error">{error}</div>}

      {/* ── Password ── */}
      <div className="card security-section">
        <div className="security-section-header">
          <div>
            <h2 className="security-section-title">
              Password
              {passwords.length > 0 && <span className="count-badge">({passwords.length})</span>}
            </h2>
            <p className="security-section-desc">
              Sign in securely using your account password. You can update your password at any time.
            </p>
          </div>
          <button className="btn-outline" onClick={() => triggerAiaAction('UPDATE_PASSWORD')}>
            Update
          </button>
        </div>

        <div className="credential-list">
          {passwords.map((c) => (
            <CredentialRow key={c.id} credential={c} label="My password" />
          ))}
          {passwords.length === 0 && <div className="empty-cred">No password set.</div>}
        </div>
      </div>

      {/* ── Authenticator App ── */}
      <div className="card security-section">
        <div className="security-section-header">
          <div>
            <h2 className="security-section-title">
              Authenticator application
              {otps.length > 0 && <span className="count-badge">({otps.length})</span>}
            </h2>
            <p className="security-section-desc">
              Sign in using a time-based verification code generated by your authenticator app.
            </p>
          </div>
          <button className="btn-outline" onClick={() => triggerAiaAction('CONFIGURE_TOTP')}>
            Set up
          </button>
        </div>

        <div className="credential-list">
          {otps.map((c) => (
            <CredentialRow
              key={c.id}
              credential={c}
              label={c.userLabel || 'Authenticator App'}
              onRemove={() => removeCredential(c.id)}
            />
          ))}
          {otps.length === 0 && <div className="empty-cred">Authenticator application is not set up.</div>}
        </div>
      </div>

      {/* ── Passkey ── */}
      <div className="card security-section">
        <div className="security-section-header">
          <div>
            <h2 className="security-section-title">
              Passkey
              {passkeys.length > 0 && <span className="count-badge">({passkeys.length})</span>}
            </h2>
            <p className="security-section-desc">
              Use your Passkey for passwordless sign in.
            </p>
          </div>
          <button className="btn-outline" onClick={() => triggerAiaAction('webauthn-register')}>
            Set up Passkey
          </button>
        </div>

        <div className="credential-list">
          {passkeys.map((c) => (
            <CredentialRow
              key={c.id}
              credential={c}
              label={c.userLabel || 'Passkey (Default Label)'}
              onRemove={() => removeCredential(c.id)}
            />
          ))}
          {passkeys.length === 0 && <div className="empty-cred">No passkeys are set up.</div>}
        </div>
      </div>
    </div>
  );
}

function CredentialRow({ credential, label, onRemove }) {
  const date = credential.createdDate ? new Date(credential.createdDate).toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit'
  }) : 'Unknown date';

  return (
    <div className="credential-row">
      <div className="credential-info">
        <div className="credential-label">{label}</div>
        <div className="credential-date">Created at {date}.</div>
        {credential.type === 'password' && <span className="badge badge-success mt-2">Active</span>}
      </div>
      {onRemove && (
        <div className="credential-actions">
          {/* <button className="btn-text">Rename</button> */}
          <button className="btn-text text-danger" onClick={onRemove}>Remove</button>
        </div>
      )}
    </div>
  );
}
